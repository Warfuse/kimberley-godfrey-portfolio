const keys = Object.keys(projects),
  caseDialog = document.querySelector("#case-dialog");
let current = 0,
  lastOpener = null;
function openProject(key, opener) {
  if (!projects[key]) return;
  lastOpener = opener?.closest("#quick-dialog")
    ? document.querySelector("#recruiter")
    : opener || lastOpener;
  current = keys.indexOf(key);
  const p = projects[key];
  document.querySelector("#case-index").textContent =
    `${String(current + 1).padStart(2, "0")} / ${String(keys.length).padStart(2, "0")} — ${p.name}`;
  document.querySelector("#case-content").innerHTML =
    `<p class="case-kicker">${p.kicker}</p><h2 class="case-title" id="case-title">${p.title}</h2><p class="case-subtitle">${p.intro}</p><div class="case-facts"><div><b>MY ROLE</b>${p.role}</div><div><b>WHEN</b>${p.time}</div><div><b>SCOPE</b>${p.scope}</div></div><div class="case-brief" aria-label="Project summary">${p.brief.map(([title, text]) => `<section><h3>${title}</h3><p>${text}</p></section>`).join("")}</div>${prototypePanel(key, p.name)}${p.image ? `<figure class="case-image"><img src="assets/${p.image}" alt="${p.caption}"><figcaption>${p.caption}</figcaption></figure>` : ""}${p.gallery ? `<details class="case-detail"><summary>Compare the original screens</summary><div class="source-gallery">${p.gallery.map(([src, title, note]) => `<figure><a href="assets/${src}" target="_blank" rel="noopener"><img loading="lazy" src="assets/${src}" alt="${title}"></a><figcaption><b>${title}</b>${note}</figcaption></figure>`).join("")}</div></details>` : ""}<details class="case-detail"><summary>My design decisions</summary>${p.sections.map(([h, t]) => `<section class="case-section"><h3>${h}</h3>${t.startsWith("<ol>") ? t : `<p>${t}</p>`}</section>`).join("")}</details><a class="case-source" href="${p.source || `https://amaplan.com/assets/portfolio-source.pdf#page=${p.start}`}" target="_blank" rel="noopener">${p.sourceLabel || `Read final portfolio · pages ${p.pages} ↗`}</a>`;
  const launch = document.querySelector("[data-launch]");
  launch.onclick = () => {
    const host = document.querySelector(".prototype-frame");
    if (host.firstChild) {
      host.replaceChildren();
      launch.textContent = "Open interactive preview ↗";
      return;
    }
    const iframe = document.createElement("iframe");
    iframe.src = `prototypes/${prototypeFiles[key]}.html`;
    iframe.title = `${p.name} working portfolio prototype`;
    iframe.setAttribute("allow", "fullscreen");
    host.appendChild(iframe);
    launch.textContent = "Close interactive preview ↑";
  };
  if (!caseDialog.open) caseDialog.showModal();
  caseDialog.scrollTop = 0;
  document.querySelector("#case-close").focus();
  history.replaceState(null, "", `#project-${key}`);
}
function closeProject() {
  document.querySelector(".prototype-frame")?.replaceChildren();
  caseDialog.close();
  history.replaceState(null, "", "#work");
  lastOpener?.focus();
}
document.querySelectorAll("[data-project]").forEach((b) =>
  b.addEventListener("click", () => {
    document.querySelector("#quick-dialog").close();
    openProject(b.dataset.project, b);
  }),
);
document.querySelector("#case-close").onclick = closeProject;
caseDialog.addEventListener("cancel", (e) => {
  e.preventDefault();
  closeProject();
});
document.querySelector("#next").onclick = () =>
  openProject(keys[(current + 1) % keys.length]);
document.querySelector("#previous").onclick = () =>
  openProject(keys[(current + keys.length - 1) % keys.length]);
const listButton = document.querySelector("#list-view"),
  exploreButton = document.querySelector("#explore-view");
function setView(list) {
  document.querySelector("#projects").classList.toggle("list", list);
  listButton.setAttribute("aria-pressed", String(list));
  exploreButton.setAttribute("aria-pressed", String(!list));
}
listButton.onclick = () => setView(true);
exploreButton.onclick = () => setView(false);
document.querySelector("#recruiter").onclick = () =>
  document.querySelector("#quick-dialog").showModal();
document.querySelector("#notes-open").onclick = () =>
  document.querySelector("#notes-dialog").showModal();
document
  .querySelectorAll("[data-close]")
  .forEach(
    (b) => (b.onclick = () => document.getElementById(b.dataset.close).close()),
  );
document.querySelectorAll("dialog").forEach((d) =>
  d.addEventListener("click", (e) => {
    if (e.target === d) {
      const r = d.getBoundingClientRect();
      if (
        e.clientX < r.left ||
        e.clientX > r.right ||
        e.clientY < r.top ||
        e.clientY > r.bottom
      )
        d === caseDialog ? closeProject() : d.close();
    }
  }),
);
const motion = document.querySelector("#motion");
const preference = matchMedia("(prefers-reduced-motion: reduce)");
let stored;
try {
  stored = localStorage.getItem("kim-reduce");
} catch {}
let reduced =
  stored === null || stored === undefined
    ? preference.matches
    : stored === "true";
function applyMotion() {
  document.documentElement.classList.toggle("reduced", reduced);
  motion.setAttribute("aria-pressed", String(reduced));
  motion.textContent = `Motion: ${reduced ? "off" : "on"}`;
}
applyMotion();
motion.onclick = () => {
  reduced = !reduced;
  applyMotion();
  try {
    localStorage.setItem("kim-reduce", String(reduced));
  } catch {}
};
preference.addEventListener("change", (e) => {
  reduced = e.matches;
  applyMotion();
});

if (location.hash.startsWith("#project-"))
  openProject(location.hash.replace("#project-", ""));

// The portrait orbit is also a project map. Pointer movement is purely decorative.
const world = document.querySelector(".portrait-world");
let framePending = false;
world.addEventListener("pointermove", (e) => {
  if (reduced || e.pointerType !== "mouse" || framePending) return;
  framePending = true;
  requestAnimationFrame(() => {
    const r = world.getBoundingClientRect();
    world.style.setProperty(
      "--drift-x",
      `${((e.clientX - r.left) / r.width - 0.5) * 8}px`,
    );
    world.style.setProperty(
      "--drift-y",
      `${((e.clientY - r.top) / r.height - 0.5) * 8}px`,
    );
    framePending = false;
  });
});
world.addEventListener("pointerleave", () => {
  world.style.setProperty("--drift-x", "0px");
  world.style.setProperty("--drift-y", "0px");
});
